; This file contains the functions for initializing the sound hardware and
; generating tones of specific frequencies using Timer1.
;
; The public functions included are:
;    PlayNote           - Sets Timer1 to generate a tone of a given frequency.
;    Init_Sound         - Initializes the hardware pin for sound output.
