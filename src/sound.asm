; --------------------------------------------------------------------------------
; PlayNote
;
; Description:       Sets Timer1 to generate a square wave of a given frequency on
;                    the OC1A pin (PB5). Invoked by game logic in Mainloop/Helpers
;                    to produce audio feedback (like score chimes) by dynamically
;                    adjusting the Timer1 frequency.
;
; Operation:         The function first checks if the input frequency is zero. If it is,
;                    it calls a helper routine to disable the timer output, silencing
;                    the speaker. If the frequency is non-zero, it calculates the
;                    required 16-bit compare match value for OCR1A using the formula:
;                    OCR1A = (500000 / frequency) - 1. This value is
;                    then written to the OCR1AH:OCR1AL register pair to produce sound.
;
; Arguments:         r17:r16 - The desired frequency in Hz. A value of 0 indicates silence.
;
; Return Values:     None.
;
; Local Variables:   r18, r19, r20 - Used to hold the 24-bit numerator for division.
;                    r22, r23 - Used for 32-bit extension of the divisor.
;
; Shared Variables:  OCR1AH, OCR1AL - The Timer1 Output Compare registers are written to.
; Global Variables:  None.
;
; Input:             A 16-bit frequency value.
; Output:            The frequency of the tone generated by Timer1 on OC1A is changed.
;
; Error Handling:    A frequency of 0 is handled by disabling the sound output.
;
; Algorithms:        Uses 24-by-16 bit unsigned integer division to calculate the
;                    timer's compare match value.
;
; Data Structures:   None.
;
; Known Bugs:        None.
;
; Limitations:       Relies on an external `Div24by16U` subroutine for division.
;                    
;
; Special Notes:     This function only sets the frequency (pitch). Timer1 must be
;                    separately configured (e.g., in CTC mode with COM1A0 set for
;                    toggle output) for a tone to be generated.
;
; Registers Changed: Flags, r18, r19, r20, r22, r23. Registers used by the
;                    `Div24by16U` and `ClearSound` subroutines are also affected.
; --------------------------------------------------------------------------------
PlayNote:
    ; Check if the input frequency is 0, which means silence.
Check:
    cpi     r17, False          ; Check the high byte of the frequency.
    brne    ComputeOCR
    cpi     r16, False          ; Check the low byte of the frequency.
    brne    ComputeOCR

    ; --- Silence Speaker ---
    ; If frequency is 0, call the routine to disable the timer output.
    rcall   ClearSound
    ret                         ; Exit the function.

ComputeOCR:
    ; Calculate OCR1A value based on the formula: OCR1A = (F_CPU / (2 * N * f)) - 1
    ; With F_CPU = 8MHz and N (prescaler) = 8:
    ; OCR1A = (8,000,000 / (16 * f)) - 1 = (SOUND_PWM_CONST / f) - 1

    ; Load the 24-bit constant numerator (SOUND_PWM_CONST) into r20:r19:r18.
    ldi     r18, low(SOUND_PWM_CONST)    ; Load low byte.
    ldi     r19, high(SOUND_PWM_CONST)   ; Load middle byte.
    ldi     r20, byte3(SOUND_PWM_CONST)  ; Load high byte.

    ; The divisor (frequency) is already in r17:r16.
    ; Extend it to 32 bits for the division routine by clearing r22 and r23.
    clr     r22
    clr     r23

    ; Call the division subroutine: (r20:r19:r18) / (r17:r16)
    ; This calculates 500,000 / Frequency.
    rcall   Div24by16U          ; Result is returned in r19:r18 (16-bit quotient).

    ; --- Finalize and Store OCR1A Value ---
    ; Subtract 1 from the result as per the CTC formula.
    subi    r18, 1              ; Subtract 1 from low byte.
    sbci    r19, 0              ; Subtract carry from high byte.

    ; Write the 16-bit result to the OCR1A register pair to set the new pitch.
    ; High byte must be written first for correct 16-bit access.
    out     OCR1AH, r19
    out     OCR1AL, r18
    ldi     r18, (1 << COM1A0)
    out     TCCR1A, r18

    ret

; --------------------------------------------------------------------------------
; Init_Sound
;
; Description:       Initializes the hardware pin (PB5/OC1A) for sound output.
;                    Called by Mainloop to configure the speaker pin as output,
;                    enabling the sound subsystem before game start.
;
; Operation:         This function configures the data direction of pin PB5 to be an
;                    output. It also contains the 'ClearSound' entry point, which
;                    clears the pin's output state, effectively disabling the sound
;                    driver.
;
; Arguments:         None.
; Return Values:     None.
;
; Local Variables:   None.
; Shared Variables:  DDRB, PORTB - I/O registers for Port B are modified.
; Global Variables:  None.
;
; Input:             None.
; Output:            Pin PB5 is configured as a low output.
;
; Error Handling:    None.
;
; Algorithms:        None.
; Data Structures:   None.
;
; Known Bugs:        None.
;
; Limitations:       None.
;
; Special Notes:     This function should be called once during system initialization.
;                    The `ClearSound` label provides a secondary entry point for
;                    other functions to use to silence the speaker.
;
; Registers Changed: r18, flags.
; --------------------------------------------------------------------------------
Init_Sound:
    ; Set PB5 (the OC1A pin) as a hardware output to speaker.
    sbi     DDRB, 5

; This label is an entry point for other functions to disable sound output.
ClearSound:
    clr     r18
    out     TCCR1A, r18
    ; Set the output on PB5 to low (0).
    cbi     PORTB, 5
    ret
